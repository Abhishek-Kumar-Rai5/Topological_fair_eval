"""Prereg §10 item 1: CTU-13 facts, written to docs/ctu13_facts.md.

For each capture folder in data/CTU-13/ (capture 42 = scenario 1, ..., 54 = scenario 13):
  - label strings and how many flows carry each class
  - infected host IPs (from the README, and as seen in the flows)
  - normal hosts = sources of at least one From-Normal flow, minus the infected IPs
Nothing here is a result; it only describes the data. Run: python scripts/ctu13_facts.py
"""
import glob
import html
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "CTU-13"
OUT = ROOT / "docs" / "ctu13_facts.md"
FIRST_CAPTURE = 42                      # capture 42 = scenario 1


def label_class(label):
    """'flow=From-Botnet-V42-TCP-CC6' -> 'From-Botnet';  'flow=Background-TCP-Attempt' -> 'Background'."""
    tokens = str(label).removeprefix("flow=").split("-")
    return "-".join(tokens[:2]) if tokens[0] in ("From", "To") else tokens[0]


def readme_facts(folder):
    """Infected IPs (lines 'IP: x (Label: Botnet)') and the bot name from the README."""
    files = glob.glob(str(folder / "README*"))
    text = html.unescape(re.sub(r"<[^>]+>", " ", Path(files[0]).read_text(errors="replace")))
    ips = re.findall(r"IP:\s*(\d+\.\d+\.\d+\.\d+)\s*\(Label:\s*Botnet\)", text)
    name = re.search(r"(?i)probable name:\s*(\S+)", text)
    return sorted(set(ips), key=lambda s: tuple(map(int, s.split(".")))), (name.group(1) if name else "?")


def flow_facts(path):
    labels, src_by_class, dst_by_class = Counter(), {}, {}
    n = 0
    for chunk in pd.read_csv(path, usecols=["SrcAddr", "DstAddr", "Label"], chunksize=500_000):
        chunk["Label"] = chunk["Label"].fillna("")
        n += len(chunk)
        labels.update(chunk["Label"].value_counts().to_dict())
        chunk["cls"] = chunk["Label"].map(label_class)
        for cls, g in chunk.groupby("cls"):
            src_by_class.setdefault(cls, set()).update(g["SrcAddr"].unique())
            dst_by_class.setdefault(cls, set()).update(g["DstAddr"].unique())
    return n, labels, src_by_class, dst_by_class


def ipkey(s):
    try:
        return tuple(map(int, s.split(".")))
    except ValueError:                      # IPv6 or odd strings sort after IPv4
        return (999, s)


def main():
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    lines = [
        "# CTU-13 facts (prereg §10 item 1)", "",
        f"Generated by `scripts/ctu13_facts.py` (git HEAD at generation: `{commit}`, pandas {pd.__version__}). "
        "Descriptive only: no scores, no results. Capture folder 42 = scenario 1, ..., 54 = scenario 13.", "",
        "**Scenario 10 (capture 51) is excluded**: its `.binetflow` is not in the official backup "
        "(see `deviations_log.md`). Its README is read for the table below, flows are not available.", "",
        "**Definitions used here.** A *host* is a source IP (`SrcAddr`), because prereg windows are built from the "
        "flows a host sends. *Infected* = IPs listed in the README as `Label: Botnet`. *Normal host* = a source IP "
        "with at least one `From-Normal` flow that is not an infected IP.", "",
    ]
    summary, details, normal_sets = [], [], []
    for folder in sorted(DATA.glob("[0-9]*"), key=lambda p: int(p.name)):
        cap = int(folder.name)
        scen = cap - FIRST_CAPTURE + 1
        infected, bot = readme_facts(folder)
        files = sorted(folder.glob("*.binetflow.xz"))
        if not files:
            summary.append(f"| {scen} | {cap} | {bot} | {len(infected)} | – | – | – | – | no `.binetflow` (excluded) |")
            details.append(f"## Scenario {scen} (capture {cap})\n\nNo `.binetflow` file. README infected IPs: {', '.join(infected)}\n")
            continue
        n, labels, src, dst = flow_facts(files[0])
        classes = Counter()
        for lab, c in labels.items():
            classes[label_class(lab)] += c
        bot_src = src.get("From-Botnet", set())
        normal = sorted(src.get("From-Normal", set()) - set(infected), key=ipkey)
        normal_sets.append(set(normal))
        sending = sorted(bot_src & set(infected), key=ipkey)
        notes = []
        if bot_src - set(infected):
            notes.append("From-Botnet flows also sent by non-listed IPs: " + ", ".join(sorted(bot_src - set(infected), key=ipkey)[:5]))
        if set(infected) - bot_src:
            notes.append(f"{len(set(infected) - bot_src)} listed infected IP(s) never send a From-Botnet flow")
        if set(normal) & bot_src:
            notes.append("normal/botnet sender overlap")
        summary.append(
            f"| {scen} | {cap} | {bot} | {len(infected)} | {len(sending)} | {len(normal)} | "
            f"{classes.get('From-Botnet', 0):,} | {classes.get('From-Normal', 0):,} | {n:,} flows; {'; '.join(notes)} |")
        d = [f"## Scenario {scen} (capture {cap}, {bot})", "",
             f"- Flows: {n:,}. Classes: " + ", ".join(f"{k} {v:,}" for k, v in sorted(classes.items(), key=lambda kv: -kv[1])),
             f"- Infected IPs (README): {', '.join(infected)}",
             f"- Infected IPs that send From-Botnet flows: {', '.join(sending)}",
             f"- Normal hosts ({len(normal)}): {', '.join(normal)}",
             "- Botnet and normal label strings (flows):"]
        for lab, c in sorted(labels.items(), key=lambda kv: -kv[1]):
            if label_class(lab) in ("From-Botnet", "To-Botnet", "From-Normal", "To-Normal"):
                d.append(f"  - `{lab}`: {c:,}")
        others = sorted({label_class(l) for l in labels} - {"From-Botnet", "To-Botnet", "From-Normal", "To-Normal"})
        d.append(f"- Other classes: {', '.join(others)}\n")
        details.append("\n".join(d))
        print(f"scenario {scen} done", file=sys.stderr, flush=True)
    common = sorted(set.intersection(*normal_sets), key=ipkey)
    lines += ["## Observations", "",
              f"- Normal hosts per scenario: {min(map(len, normal_sets))} to {max(map(len, normal_sets))}. "
              f"Distinct normal IPs over all {len(normal_sets)} scenarios: {len(set.union(*normal_sets))}. "
              f"Normal IPs present in every scenario: {', '.join(common)}. The same few lab machines recur, so normal-host windows are not independent across scenarios.",
              "- Botnet label strings name the protocol or traffic type (for example `UDP-DNS`, `TCP-Attempt-SPAM`, "
              "`TCP-CC1-HTTP-Not-Encrypted`, `HTTP-Binary-Download`, `HTTP-Ad`), not one behaviour name each. "
              "Whether this counts as 'strings name behaviours' (prereg §2) is a decision for E4.",
              "- Some scenarios have From-Botnet flows sent by non-listed IPs (see Notes). "
              "Not investigated further. Prereg §2 makes a window positive only for an infected host, so these IPs are not positive hosts.", ""]
    lines += ["## Summary", "",
              "| Scenario | Capture | Bot (README) | Infected IPs (README) | Infected IPs sending From-Botnet | Normal hosts | From-Botnet flows | From-Normal flows | Notes |",
              "|---|---|---|---|---|---|---|---|---|"] + summary + [""] + details
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
