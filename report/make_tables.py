"""Build report/records.bib and report/tables/core_papers.tex from the literature master CSV.

Run from the repo root:  python report/make_tables.py literature/tda_records_master.csv
Same core-set rule and outcome normalisation as literature/make_figs.py, so the table matches Figures 1-2.
"""
import re, sys, pathlib
import pandas as pd

src = sys.argv[1] if len(sys.argv) > 1 else "literature/tda_records_master.csv"
here = pathlib.Path(__file__).parent
m = pd.read_csv(src, dtype=str, keep_default_na=False)

# ---------- bibliography: one @misc entry per record, key = record ID ----------
OVERRIDE = {  # records whose CSV fields contain CJK text or extraction notes
    "B08": dict(authors="Junpei Kashiwagura; Masaki Narita; Toshimitsu Inomata; Eiji Sugino; Shintaro Imai",
                title="A study on topological data analysis of darknet monitoring packets (in Japanese)",
                venue="Computer Security Symposium 2017 (CSS2017, IPSJ), pp. 1246--1250"),
    "N11": dict(title="TopoSMOTE (Chinese-language article; exact title not captured)",
                venue="Science Technology and Engineering 25(19):8142--8150 (in Chinese)"),
}

def tex(s):
    s = re.sub(r"[　-鿿＀-￯]+", "", s)          # drop CJK characters
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$")]:
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()

def venue(v):
    return tex(v.split(";")[0].rstrip(". "))

def year(y):
    hit = re.search(r"(19|20)\d\d", y)
    return hit.group(0) if hit else ""

entries = []
for r in m.itertuples():
    o = OVERRIDE.get(r.id, {})
    authors = " and ".join(tex(a) for a in o.get("authors", r.authors).split(";") if a.strip())
    f = {"author": authors, "title": "{" + tex(o.get("title", r.title)) + "}",
         "howpublished": o.get("venue", venue(r.venue)), "year": year(r.year)}
    if r.doi: f["doi"] = r.doi.strip()
    if r.arxiv: f.update(eprint=r.arxiv.strip(), archivePrefix="arXiv")
    if r.url and not r.doi: f["url"] = r.url.strip()
    f["note"] = f"Record {r.id}"
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items() if v)
    entries.append(f"@misc{{{r.id},\n{body}\n}}")
(here / "records.bib").write_text("% Generated by make_tables.py from the master CSV. Do not edit by hand.\n\n"
                                  + "\n\n".join(entries) + "\n")

# ---------- appendix table of the 32 core papers ----------
GROUP = {g: ids.split() for g, ids in {
    "A": "C01 C02 H04 I03", "B": "N01 D04 N10 N12 Q06", "C": "N11 C07 H05 B07 B03",
    "D": "B01 B08 D01 I02 J07 G01 I04 J05 C06 Q05", "E": "D02 N03 N07 N09 B05 B06 B09 C08"}.items()}
grp = {i: g for g, ids in GROUP.items() for i in ids}

def norm(o, ver):  # identical to make_figs.py
    o = o.strip()
    if o in ("", "U"): return "Unclear"
    if o.startswith("Untested"): return "Untested"
    if ver == "abstract" or "abstract" in o.lower(): return "Claimed"
    return "Tied" if o.startswith("Tied") else o.split()[0]

core = m[m.inclusion_status.str.startswith("core") & ~m.inclusion_status.str.startswith("core-method") & (m.id != "D03")].copy()
assert len(core) == 32 and set(core.id) == set(grp), "core set changed: update GROUP"
order = ["S1", "S2", "S3", "S4", "S5", "S6", "S7", "S8", "I1", "I2", "I3", "I4", "I5", "I6"]
core["ci"] = core.cluster.map(order.index)
core = core.sort_values(["ci", "id"])

rows = []
for r in core.itertuples():
    first = r.authors.split(";")[0].strip().split()[-1] if r.authors.strip() else "?"
    if r.id == "B08": first = "Kashiwagura"
    who = tex(first) + (" et al." if ";" in r.authors else "")
    title = tex(OVERRIDE.get(r.id, {}).get("title", r.title))
    title = title if len(title) <= 70 else title[:67].rsplit(" ", 1)[0] + "\\ldots"
    iso = r.ISO.split()[0] if r.ISO.strip() and r.ISO.split()[0] != "U" else "--"
    use = r.USE if r.USE.strip() and r.USE != "U" else "--"
    read = "full" if r.verification == "full_text" else "abs."
    rows.append(f"{r.id} & {title} & {who}, {year(r.year)}~\\cite{{{r.id}}} & {r.cluster} & {grp[r.id]} & "
                f"{use} & {iso} & {norm(r.OUT, r.verification)} & {read} \\\\")
(here / "tables").mkdir(exist_ok=True)
(here / "tables" / "core_papers.tex").write_text("% Generated by make_tables.py. Do not edit by hand.\n" + "\n".join(rows) + "\n")
print(f"{len(entries)} bib entries, {len(rows)} core rows")
